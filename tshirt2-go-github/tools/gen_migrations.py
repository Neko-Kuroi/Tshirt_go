"""Flask 版 app/schema.py の MIGRATIONS から、Go 側の migrations.go と testdata/migrations.json を生成する。

使い方: python tools/gen_migrations.py <Flask版の schema.py のパス>
手で書き写さないための道具。schema.py が変わったら再実行する(差分が出たら、移植漏れ)。
"""
import importlib.util
import json
import pathlib
import sys

src = pathlib.Path(sys.argv[1])
spec = importlib.util.spec_from_file_location("flask_schema", src)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
migs = list(mod.MIGRATIONS)

root = pathlib.Path(__file__).resolve().parent.parent
for i, sql in enumerate(migs, 1):
    assert "`" not in sql, f"migration {i} contains a backtick"

lines = [
    "// Code generated by tools/gen_migrations.py from Flask 版 app/schema.py (MIGRATIONS). DO NOT EDIT.",
    "",
    "package db",
    "",
    "// Migrations は schema.py の MIGRATIONS と同一のSQL。適用済みの番号は PRAGMA user_version に保存される。",
    "var Migrations = []string{",
]
for i, sql in enumerate(migs, 1):
    lines.append(f"\t// {i}")
    lines.append("\t`" + sql + "`,")
lines.append("}")
lines.append("")
(root / "internal/db/migrations.go").write_text("\n".join(lines), encoding="utf-8")
(root / "internal/db/testdata/migrations.json").write_text(
    json.dumps(migs, ensure_ascii=False, indent=1), encoding="utf-8")
print(f"{len(migs)} migrations written")
